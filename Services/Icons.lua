local function normalize(name)
    local key = string.lower(name)
    key = key:gsub("[%s_]+", "-")
    key = key:gsub("%-+", "-")
    return key:gsub("^%-", ""):gsub("%-$", "")
end

local compactNames = {}
for name in pairs(registry) do
    compactNames[name:gsub("%-", "")] = name
end

local function resolveName(name)
    if type(name) ~= "string" then return nil end
    local key = normalize(name)
    key = aliases[key] or compactNames[key] or key
    return registry[key] and key or nil
end

local function isValidContentId(value)
    return value:match("^rbxassetid://%d+$")
        or value:match("^rbxasset://.+")
        or value:match("^https?://.+")
end

local Icons = {}

function Icons.Get(name)
    if type(name) == "number" and name > 0 then
        return "rbxassetid://" .. math.floor(name)
    end
    if type(name) == "string" then
        local key = resolveName(name)
        if key then return registry[key] end
        if isValidContentId(name) then return name end
    end
    return registry.info
end

function Icons.Exists(name)
    return resolveName(name) ~= nil
end

function Icons.List()
    local names = {}
    for name in pairs(registry) do table.insert(names, name) end
    table.sort(names)
    return names
end

return Icons
